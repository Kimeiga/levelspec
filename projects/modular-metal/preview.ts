import * as THREE from "three";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { OrbitControls } from "three/addons/controls/OrbitControls.js";
import { RoomEnvironment } from "three/addons/environments/RoomEnvironment.js";

const renderer = new THREE.WebGLRenderer({ antialias: true });
renderer.setPixelRatio(Math.min(devicePixelRatio, 2));
renderer.setSize(innerWidth, innerHeight);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure = 1;
renderer.shadowMap.enabled = true;
renderer.shadowMap.type = THREE.PCFShadowMap;
document.body.append(renderer.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color("#252e34");
const pmrem = new THREE.PMREMGenerator(renderer);
const room = new RoomEnvironment();
const environment = pmrem.fromScene(room, .04);
scene.environment = environment.texture;
scene.environmentIntensity = .85;
room.dispose(); pmrem.dispose();
const camera = new THREE.PerspectiveCamera(38, innerWidth / innerHeight, .05, 40);
camera.position.set(4.15, 2.9, 3.6);
const controls = new OrbitControls(camera, renderer.domElement);
controls.target.set(1.75, .65, -1.1);
controls.update();
const key = new THREE.DirectionalLight(0xfff3df, 2);
key.position.set(-1,5,3); key.castShadow = true;
key.shadow.mapSize.set(2048,2048);
Object.assign(key.shadow.camera, {left:-5,right:5,top:5,bottom:-5,near:.1,far:20});
key.shadow.normalBias = .015;
scene.add(key);
scene.add(new THREE.HemisphereLight(0xd7eaff,0x786852,.7));
const gltf = await new GLTFLoader().loadAsync("/generated/modular-metal/study.glb");
gltf.scene.traverse(object => { if (object instanceof THREE.Mesh) { object.castShadow = true; object.receiveShadow = true; } });
scene.add(gltf.scene);
let angle = 0;
document.querySelector("#light")!.addEventListener("click", () => {
  angle += Math.PI / 2;
  scene.environmentRotation.y = angle;
  key.position.set(Math.sin(angle) * 4, 5, Math.cos(angle) * 4);
});
window.addEventListener("resize", () => { camera.aspect = innerWidth / innerHeight; camera.updateProjectionMatrix(); renderer.setSize(innerWidth, innerHeight); });
renderer.setAnimationLoop(() => { controls.update(); renderer.render(scene, camera); });
Object.assign(window, { metalStudy: { scene, camera, controls } });
document.body.dataset.ready = "true";
