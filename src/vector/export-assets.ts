import type { CompiledLevel } from "./types.ts";
import { aborted } from "./types.ts";
import { materialTextures } from "./materials.ts";
import { withBuiltinMaterialImages } from "../materials/images.ts";

/** Materials actually referenced by visible triangles, excluding declarations and collision proxies. */
function visibleMaterialIds(level: CompiledLevel): Set<string> {
  return usedExportMaterialIds(level, [...new Set(level.mesh.surfaces)]
    .filter(index => level.surfaces[index].visible !== false));
}

export type ExportFormat = "glb" | "gltf" | "fbx" | "bsp";
export interface ExportAsset {
  bytes: Uint8Array;
  mimeType: "image/png" | "image/jpeg";
  hash: string;
  file: string;
}
export interface ExportOptions {
  /** Collision exports include proxies and omit visual-only detail. */
  purpose?: "visual" | "collision";
  assets?: Record<string, ExportAsset>;
}
export type ExportFiles = Record<string, string | Uint8Array>;

/** Resolves materials for selected surfaces, including the explicit fallback for unknown runtime finishes. */
export function usedExportMaterialIds(level: CompiledLevel, surfaceIndices: Iterable<number>): Set<string> {
  const declared = new Set(level.document.materials.map(material => material.id));
  return new Set(Array.from(surfaceIndices, index => {
    const id = level.surfaces[index].material;
    return declared.has(id) ? id : "default";
  }));
}

/** Maps compiler-generated references to portable image files without serializing encoded bytes. */
export function generatedImageManifest(level: CompiledLevel): Record<string, Omit<ExportAsset, "bytes">> {
  return Object.fromEntries(Object.entries(level.generatedImages ?? {}).map(
    ([reference, { bytes: _bytes, ...metadata }]) => [reference, metadata],
  ));
}

export function exportName(id: string): string {
  return id.replace(/[^a-zA-Z0-9_-]/g, "_").slice(0, 100) || "level";
}

/** Resolves generated bytes before host-owned source I/O; compile-only height inputs are excluded. */
export async function resolveExportAssets(
  level: CompiledLevel,
  read?: (reference: string, signal?: AbortSignal) => Promise<Uint8Array>,
  signal?: AbortSignal,
): Promise<Record<string, ExportAsset>> {
  const assets: Record<string, ExportAsset> = Object.create(null);
  const used = visibleMaterialIds(level);
  const load = read ?? withBuiltinMaterialImages();
  for (const material of level.document.materials.filter(material => used.has(material.id))) for (const ref of materialTextures(material)) {
    if (assets[ref]) continue;
    aborted(signal);
    let bytes: Uint8Array;
    try {
      bytes = level.generatedImages?.[ref]?.bytes ?? await load(ref, signal);
    } catch (error) {
      throw new Error(
        `Material ${material.id}: cannot resolve texture "${ref}": ${(error as Error).message}`,
      );
    }
    aborted(signal);
    const png = [137, 80, 78, 71, 13, 10, 26, 10].every(
      (v, i) => bytes[i] === v,
    );
    const jpeg = bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255;
    if (!png && !jpeg)
      throw new Error(
        `Material ${material.id}: "${ref}" must be a PNG or JPEG image.`,
      );
    const hash = Array.from(
      new Uint8Array(
        await crypto.subtle.digest("SHA-256", Uint8Array.from(bytes).buffer),
      ),
      (n) => n.toString(16).padStart(2, "0"),
    ).join("");
    assets[ref] = {
      bytes,
      hash,
      mimeType: png ? "image/png" : "image/jpeg",
      file: `textures/${hash}.${png ? "png" : "jpg"}`,
    };
  }
  return assets;
}

export function assertExportable(
  level: CompiledLevel,
  options: ExportOptions = {},
) {
  if (level.diagnostics.some((d) => d.severity === "error"))
    throw new Error(
      "Cannot export invalid geometry. Resolve compilation errors first.",
    );
  if (options.purpose !== "collision" && !level.mesh.indices.length)
    throw new Error("Cannot export an empty model.");
  const used = visibleMaterialIds(level);
  for (const m of level.document.materials.filter(material => used.has(material.id))) for (const reference of materialTextures(m))
    if (
      options.purpose !== "collision" &&
      !options.assets?.[reference] && !level.generatedImages?.[reference]
    )
      throw new Error(
        `Material ${m.id}: unresolved texture "${reference}". Supply resolved export assets.`,
      );
}

export function exportMetadata(
  level: CompiledLevel,
  formats: ExportFormat[],
  purpose: "visual" | "collision" = "visual",
  includedSurfaceIndices = [...new Set(level.mesh.surfaces)],
) {
  return {
    version: 3,
    ...(level.provenance ? { architecturalProvenance: level.provenance } : {}),
    purpose,
    includedSurfaceIndices,
    includedParts: [
      ...new Set(
        includedSurfaceIndices
          .map((index) => level.surfaces[index]?.mesh)
          .filter(Boolean),
      ),
    ],
    id: level.document.id,
    name: level.document.name,
    geometryHash: level.geometryHash,
    spatialVolumes: level.spatialVolumes,
    terrainTiles: level.terrainTiles,
    ...(level.terrainTiles?.length ? { physicalMesh: level.physicalMesh } : {}),
    coordinates: {
      source: "right-handed Z-up metres",
      glb: "Y-up metres: (x,z,-y)",
      gltf: "Y-up metres: (x,z,-y)",
      fbx: "Y-up, -Z forward; metre scene with FBX unit metadata",
      bsp: "Z-up, 32 units per metre",
    },
    formats,
    parts: level.parts,
    surfaces: level.surfaces,
    materials: level.document.materials,
    ...(level.generatedImages ? { generatedImages: generatedImageManifest(level) } : {}),
    markers: level.document.markers,
    assets: level.document.assets,
    references: level.document.references,
    routes: level.document.routes,
    water: level.water,
    boat: level.document.boat,
    waterNavigation: level.waterNavigation,
    validation: level.document.validation ?? "playable",
    repairs: level.repairs ?? [],
    links: level.document.links,
    lights: level.document.lights,
    sky: level.document.sky,
    layers: level.document.layers.map(({ id, label }) => ({ id, label })),
    atlas: level.atlas,
    uvChannels: { material: 0, lightmap: level.mesh.uv1 ? 1 : null },
    uvCoordinates: {
      source: "bottom-left",
      glb: "(u, 1-v); authored +Y tangent frame preserved",
      gltf: "(u, 1-v); authored +Y tangent frame preserved",
      fbx: "unchanged",
    },
    lighting:
      "Lightmap coordinates only; baked illumination is not packaged or bound automatically.",
  };
}
