/** Captures real balcony prop emitters with identical supports before and after adoption. */
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {Matrix4} from 'three';
import {compile,createArchitecture,resolveExportAssets,toGLB,collisionMesh} from '../../src/architecture/index.ts';
import {withBuiltinMaterialImages} from '../../src/materials/images.ts';
import {kitMaterials,kitFinishes} from '../../src/dressing/kit.ts';
import {KitMesh} from '../../src/dressing/kit-mesh.ts';
import {Pen} from '../../src/dressing/pen.ts';
import {pottedPlant} from '../../src/dressing/kowloon/fixtures.ts';
import {washing,hangers} from '../../src/dressing/kowloon/laundry.ts';
import {Rng} from '../../src/generate/rng.ts';
import {validateBytes} from 'gltf-validator';
import assert from 'node:assert/strict';
const destination=process.argv[2];
if(!destination)throw new Error('Pass a new output directory');
await mkdir(destination,{recursive:false});
const level=await compile(createArchitecture('balcony-props'),{navigation:false});
kitMaterials(level);level.mesh.colors=[];
const physics=JSON.stringify(collisionMesh(level));
const pen=new Pen(new KitMesh(level,'balcony','props',kitFinishes(level,undefined,'builtin:concrete').materials,{maximumTriangles:100000}),'balcony',new Matrix4(),false);
pen.box('concrete',[0,-.65,-.14],[6.3,.55,0],[.66,.67,.63]);
pen.box('concrete',[0,-.65,0],[6.3,-.53,2.65],[.65,.66,.62]);
for(const x of [0,6.26])pen.bar('metal',[x,.5,0],[x,.5,1.02],.035,[.45,.43,.39]);
pen.bar('metal',[0,.5,1.02],[6.3,.5,1.02],.035,[.45,.43,.39]);
for(let x=.22;x<6.3;x+=.27)pen.bar('metal',[x,.5,0],[x,.5,1],.015,[.45,.43,.39]);
for(let i=0;i<7;i++)pottedPlant(pen.into('plants'),[.42+i*.86,.13,0],new Rng('balcony-plant-'+i));
pen.tube('paint',[[.15,-.18,2.37],[6.15,-.18,2.37]],.006,[.35,.32,.26],6);
washing(pen.move(0,-.18,0).into('washing'),.2,6.1,2.37,new Rng('balcony-wash-4'),{fill:1,drop:1.2,support:'line'});
pen.tube('paint',[[.2,.08,1.15],[6.1,.08,1.15]],.014,[.4,.32,.22],6);
washing(pen.move(0,.08,0).into('pole-washing'),.2,6.1,1.15,new Rng('balcony-pole-3'),{fill:.55,drop:.85,support:'pole'});
assert.equal(JSON.stringify(collisionMesh(level)),physics);
const bytes=toGLB(level,{assets:await resolveExportAssets(level,withBuiltinMaterialImages(reference=>readFile(reference)))});
const validation=await validateBytes(bytes);assert.equal(validation.issues.numErrors,0);
await writeFile(destination+'/context.glb',bytes);
const paths=['src/dressing/kowloon/fixtures.ts','src/dressing/kowloon/laundry.ts','src/dressing/kit.ts','src/materials/catalog.ts','src/dressing/kowloon/balcony-props.ts','src/dressing/kowloon/assets/balcony-props.json','projects/kowloon-balcony-props/build-context.mjs',...['plants','cloth'].flatMap(group=>['','-normal','-properties'].map(suffix=>'src/materials/library/balcony-'+group+suffix+'.png'))];
await writeFile(destination+'/context.json',JSON.stringify({triangles:level.mesh.indices.length/3,bytes:bytes.length,collisionUnchanged:true,validation:validation.issues,hashes:Object.fromEntries(await Promise.all(paths.map(async p=>[p,createHash('sha256').update(await readFile(p)).digest('hex')]))),glbHash:createHash('sha256').update(bytes).digest('hex')},null,2));
console.log(JSON.stringify({destination,triangles:level.mesh.indices.length/3,bytes:bytes.length}));
