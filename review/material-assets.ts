import * as THREE from "three";
import { builtinMaterialURL } from "../src/materials/images.ts";
import type { CompiledLevel } from "../src/vector/types.ts";

/** Owns decoded material images and their GPU textures for one published preview. */
export class ReviewTextures {
  private textures = new Map<string, THREE.Texture>();
  private images = new Map<HTMLImageElement, Map<boolean, THREE.Texture>>();

  /** Retrieves a material slot using its declared color-space interpretation. */
  get(reference: string, color: boolean): THREE.Texture | undefined {
    return this.textures.get(`${color ? "color" : "linear"}/${reference}`);
  }

  /** Binds an alias, sharing the decoded image's texture within each color space. */
  add(reference: string, color: boolean, image: HTMLImageElement) {
    let interpretations = this.images.get(image);
    if (!interpretations) {
      interpretations = new Map();
      this.images.set(image, interpretations);
    }
    let texture = interpretations.get(color);
    if (!texture) {
      texture = new THREE.Texture(image);
      texture.colorSpace = color ? THREE.SRGBColorSpace : THREE.NoColorSpace;
      texture.wrapS = texture.wrapT = THREE.RepeatWrapping;
      // Three.js clamps this request to the device limit; preserve detail on oblique shelves and floors.
      texture.anisotropy = 8;
      texture.needsUpdate = true;
      interpretations.set(color, texture);
    }
    this.textures.set(`${color ? "color" : "linear"}/${reference}`, texture);
  }

  /** Reuploads retained decoded images after the browser restores its graphics context. */
  restore() {
    for (const interpretations of this.images.values())
      for (const texture of interpretations.values()) texture.needsUpdate = true;
  }

  /** Releases all GPU resources; safe for abandoned candidates as well as published scenes. */
  dispose() {
    for (const interpretations of this.images.values())
      for (const texture of interpretations.values()) texture.dispose();
    this.textures.clear();
    this.images.clear();
  }
}

/** Decodes an image before publication and abandons pending decoding on cancellation. */
async function decodeImage(url: string, signal?: AbortSignal): Promise<HTMLImageElement> {
  signal?.throwIfAborted();
  const image = new Image();
  image.crossOrigin = "anonymous";
  image.decoding = "async";
  const cancel = () => { image.src = ""; };
  signal?.addEventListener("abort", cancel, { once: true });
  try {
    image.src = url;
    await image.decode();
    signal?.throwIfAborted();
    return image;
  } finally {
    signal?.removeEventListener("abort", cancel);
  }
}

/** Resolves only declared companion names, including file-picker basename aliases. */
function companionURL(urls: Record<string, string>, reference: string): string | undefined {
  const normalized = reference.replaceAll("\\", "/").replace(/^\.\//, "");
  if (Object.hasOwn(urls, normalized)) return urls[normalized];
  const basename = normalized.split("/").at(-1)!;
  return Object.hasOwn(urls, basename) ? urls[basename] : undefined;
}

/**
 * Stages every visible receiver's material image without changing the published
 * scene. Generated bytes take precedence over explicitly supplied companion URLs.
 */
export async function prepareReviewTextures(
  level: CompiledLevel,
  urls: Record<string, string>,
  signal?: AbortSignal,
): Promise<ReviewTextures> {
  const textures = new ReviewTextures();
  const visibleMaterials = new Set<string>();
  for (const index of new Set(level.mesh.surfaces)) {
    const surface = level.surfaces[index];
    if (surface.visible !== false) visibleMaterials.add(surface.material);
  }
  const slots = new Map<string, Set<boolean>>();
  const decoded = new Map<string, HTMLImageElement>();
  for (const material of level.document.materials) {
    if (!visibleMaterials.has(material.id)) continue;
    for (const [reference, color] of [
      [material.texture, true],
      [material.normalTexture, false],
      [material.metallicRoughnessTexture, false],
    ] as const) {
      if (!reference) continue;
      const interpretations = slots.get(reference) ?? new Set<boolean>();
      interpretations.add(color);
      slots.set(reference, interpretations);
    }
  }
  try {
    for (const [reference, interpretations] of slots) {
      signal?.throwIfAborted();
      const generated = level.generatedImages && Object.hasOwn(level.generatedImages, reference)
        ? level.generatedImages[reference] : undefined;
      let generatedURL: string | undefined;
      try {
        const companion = generated ? undefined : builtinMaterialURL(reference) ?? companionURL(urls, reference);
        if (!generated && !companion) throw new Error(`Supply companion image: ${reference}`);
        const identity = generated ? `generated/${generated.hash}` : `url/${new URL(companion!, document.baseURI).href}`;
        let image = decoded.get(identity);
        if (!image) {
          if (generated) generatedURL = URL.createObjectURL(
            new Blob([new Uint8Array(generated.bytes)], { type: generated.mimeType }),
          );
          image = await decodeImage(generatedURL ?? companion!, signal);
          decoded.set(identity, image);
        }
        for (const color of interpretations) textures.add(reference, color, image);
      } catch (error) {
        signal?.throwIfAborted();
        throw new Error(`Unable to decode companion image "${reference}": ${(error as Error).message}`);
      } finally {
        if (generatedURL) URL.revokeObjectURL(generatedURL);
      }
    }
    signal?.throwIfAborted();
    return textures;
  } catch (error) {
    textures.dispose();
    throw error;
  }
}
